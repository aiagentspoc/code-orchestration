class PipelineExitCode(IntEnum):
    """Standardized pipeline CLI error and exit codes."""

    SUCCESS = 0
    NO_UPDATES = 1
    MCP_ERROR = 2
    PARSER_ERROR = 3
    PERSISTENCE_ERROR = 4
